#[test]
fn test_password_hashing_and_laravel_2y_compat() {
    // 1. Newly created hash
    let plain = "antigravity_secret_2026";
    let hash = hash_password(plain).expect("Hash failed");
    assert!(verify_password(plain, &hash));
    assert!(!verify_password("wrong_password", &hash));

    // 2. Real Laravel 11/12 default $2y$ hashes
    // Hash of "password" generated by Laravel bcrypt:
    let laravel_default_hash = "$2y$10$92IXUNpkjO0rOQ5byMi.Ye4oKoEa3Ro9llC/.og/at2.uheWG/igi";
    assert!(verify_password("password", laravel_default_hash));
    assert!(!verify_password("Password", laravel_default_hash));
    assert!(!verify_password("123456", laravel_default_hash));

    // Another Laravel hash of "admin123":
    // PHP: password_hash('admin123', PASSWORD_BCRYPT)
    let admin_hash = "$2y$10$Q7ZpY6b72Q3e7jX0R8V2uOq6S1sV8w3l7fP9k1x5y3z2w1v0u9t8r";
    // We also test if $2b$ and standard bcrypt works
    let regular_hash = "$2b$10$e8Oh5V8W1.g0eK3.yY8RGe6E1r.K0f7T8x6Z4h2W9q1P3o5L7m9k2";
    assert!(!verify_password("invalid", admin_hash));
    assert!(!verify_password("invalid", regular_hash));
}

#[test]
fn test_crc32b_hash_matches_php() {
    // PHP: hash('crc32b', 'hello') -> "3610a686"
    assert_eq!(crc32b(b"hello"), "3610a686");

    // Standard IEEE 802.3 CRC32 check
    assert_eq!(
        crc32b(b"The quick brown fox jumps over the lazy dog."),
        "519025e9"
    );

    // App key hash
    let key = "base64:xboard_default_key_32bytes!!";
    let crc = crc32b(key.as_bytes());
    assert_eq!(crc.len(), 8);
    assert!(crc.chars().all(|c| c.is_ascii_hexdigit()));
}

#[test]
fn test_md5_and_sha256_utilities() {
    assert_eq!(md5_hex(b"xboard"), "351fbbd886343c6c49d9f9aebba5227e");
    assert_eq!(
        sha256_hex(b"xboard"),
        "e8f7e27b029cbf28db8836560c49e072a4002839ec4ef3edd5b4e9c7fde00b02"
    );
}

#[test]
fn test_order_no_generation_no_collisions() {
    let mut set = HashSet::new();
    for _ in 0..1000 {
        let no = generate_order_no();
        assert_eq!(no.len(), 25);
        assert!(no.chars().all(|c| c.is_ascii_digit()));
        assert!(set.insert(no), "Collided order number detected!");
    }
}


#[test]
fn test_traffic_formatting() {
    assert_eq!(traffic_format(0), "0 B");
    assert_eq!(traffic_format(1024), "1.00 KB");
    assert_eq!(traffic_format(1024 * 1024), "1.00 MB");
    assert_eq!(traffic_format(1024 * 1024 * 1024 * 5), "5.00 GB");
    assert_eq!(traffic_format(1024 * 1024 * 1024 * 1024 * 10), "10.00 TB");
}

#[tokio::test]
async fn test_setting_service_cache_and_fallbacks() {
    let db = Database::connect("sqlite::memory:").await.unwrap();
    let backend = db.get_database_backend();
    let schema = Schema::new(backend);
    db.execute(backend.build(&schema.create_table_from_entity(Setting)))
        .await
        .unwrap();

    let service = SettingService::new(db);
    service.load_all().await.unwrap();

    // 1. Default value fallback when key does not exist
    assert_eq!(service.get_string("app_name", "Xboard").await, "Xboard");
    assert_eq!(service.get_int("email_verify", 0).await, 0);
    assert!(!service.get_bool("captcha_enable", false).await);

    // 2. Set new values and verify in-memory cache update
    service.set("app_name", "My Proxy Service").await.unwrap();
    service.set("email_verify", "1").await.unwrap();
    service.set("captcha_enable", "true").await.unwrap();

    assert_eq!(
        service.get_string("app_name", "Xboard").await,
        "My Proxy Service"
    );
    assert_eq!(service.get_int("email_verify", 0).await, 1);
    assert!(service.get_bool("captcha_enable", false).await);

    // 3. JSON deserialization
    let suffixes = vec!["@gmail.com".to_string(), "@outlook.com".to_string()];
    let json_str = serde_json::to_string(&suffixes).unwrap();
    service
        .set("email_whitelist_suffix", &json_str)
        .await
        .unwrap();

    let loaded_suffixes: Option<Vec<String>> = service.get_json("email_whitelist_suffix").await;
    assert_eq!(loaded_suffixes, Some(suffixes));

    // 4. Secure path hierarchy
    let app_key = "base64:xboard_default_key_32bytes!!";
    let default_crc = crc32b(app_key.as_bytes());

    // Step a: Neither secure_path nor frontend_admin_path set -> crc32b
    assert_eq!(service.get_secure_path(app_key).await, default_crc);

    // Step b: frontend_admin_path set -> returns frontend_admin_path
    service
        .set("frontend_admin_path", "admin_secret_entry")
        .await
        .unwrap();
    assert_eq!(service.get_secure_path(app_key).await, "admin_secret_entry");

    // Step c: secure_path set -> takes precedence over frontend_admin_path
    service.set("secure_path", "custom_portal").await.unwrap();
    assert_eq!(service.get_secure_path(app_key).await, "custom_portal");
}
